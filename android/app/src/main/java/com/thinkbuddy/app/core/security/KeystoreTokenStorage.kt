package com.thinkbuddy.app.core.security

import android.content.Context
import android.security.keystore.KeyGenParameterSpec
import android.security.keystore.KeyProperties
import android.util.Base64
import java.security.KeyStore
import javax.crypto.Cipher
import javax.crypto.KeyGenerator
import javax.crypto.SecretKey
import javax.crypto.spec.GCMParameterSpec

/**
 * Modern hardware-backed AES-GCM secure token storage using the Android Keystore system.
 * Hardware-backed Android Keystore storage satisfying Rule 17.
 *
 * Enforces:
 * 1. Fresh cryptographically random 12-byte IV per encryption operation.
 * 2. Automatic lost-key sign-out: if the Keystore key is lost, revoked, or invalidated,
 *    stored credentials are automatically cleared and the sign-out callback is triggered.
 */
class KeystoreTokenStorage(context: Context) {

    private val prefs = context.getSharedPreferences(PREFS_NAME, Context.MODE_PRIVATE)
    private val keyStore = KeyStore.getInstance(KEYSTORE_PROVIDER).apply { load(null) }

    var onLostKeySignOut: (() -> Unit)? = null

    init {
        ensureKeyExists()
    }

    private fun ensureKeyExists() {
        try {
            if (!keyStore.containsAlias(KEY_ALIAS)) {
                val keyGenerator = KeyGenerator.getInstance(
                    KeyProperties.KEY_ALGORITHM_AES,
                    KEYSTORE_PROVIDER
                )
                val spec = KeyGenParameterSpec.Builder(
                    KEY_ALIAS,
                    KeyProperties.PURPOSE_ENCRYPT or KeyProperties.PURPOSE_DECRYPT
                )
                    .setBlockModes(KeyProperties.BLOCK_MODE_GCM)
                    .setEncryptionPaddings(KeyProperties.ENCRYPTION_PADDING_NONE)
                    .setKeySize(256)
                    .build()
                keyGenerator.init(spec)
                keyGenerator.generateKey()
            }
        } catch (e: Exception) {
            handleLostKey()
        }
    }

    private fun getSecretKey(): SecretKey {
        return keyStore.getKey(KEY_ALIAS, null) as SecretKey
    }

    /**
     * Encrypts plainText using AES-GCM with a fresh random 12-byte IV for every invocation.
     */
    fun encrypt(plainText: String): String {
        val cipher = Cipher.getInstance(TRANSFORMATION)
        cipher.init(Cipher.ENCRYPT_MODE, getSecretKey())
        val iv = cipher.iv // Fresh IV generated by KeyStore provider
        val cipherText = cipher.doFinal(plainText.toByteArray(Charsets.UTF_8))
        // Combine fresh IV (12 bytes) + cipherText
        val combined = ByteArray(iv.size + cipherText.size)
        System.arraycopy(iv, 0, combined, 0, iv.size)
        System.arraycopy(cipherText, 0, combined, iv.size, cipherText.size)
        return Base64.encodeToString(combined, Base64.NO_WRAP)
    }

    /**
     * Decrypts encryptedBase64. If the key is invalidated or lost, triggers lost-key sign-out.
     */
    fun decrypt(encryptedBase64: String): String? {
        return try {
            val combined = Base64.decode(encryptedBase64, Base64.NO_WRAP)
            if (combined.size < GCM_IV_LENGTH) return null

            val iv = combined.copyOfRange(0, GCM_IV_LENGTH)
            val cipherText = combined.copyOfRange(GCM_IV_LENGTH, combined.size)

            val cipher = Cipher.getInstance(TRANSFORMATION)
            val spec = GCMParameterSpec(GCM_TAG_LENGTH, iv)
            cipher.init(Cipher.DECRYPT_MODE, getSecretKey(), spec)
            val plainBytes = cipher.doFinal(cipherText)
            String(plainBytes, Charsets.UTF_8)
        } catch (e: Exception) {
            // KeyPermanentlyInvalidatedException, UnrecoverableKeyException, or AEADBadTagException
            handleLostKey()
            null
        }
    }

    private fun handleLostKey() {
        try {
            clear()
        } catch (_: Exception) {}
        onLostKeySignOut?.invoke()
    }

    fun saveTokens(accessToken: String, refreshToken: String?, userId: String?, role: String?) {
        prefs.edit()
            .putString(KEY_ACCESS_TOKEN, encrypt(accessToken))
            .apply {
                if (refreshToken != null) putString(KEY_REFRESH_TOKEN, encrypt(refreshToken))
                if (userId != null) putString(KEY_USER_ID, encrypt(userId))
                if (role != null) putString(KEY_ROLE, encrypt(role))
            }
            .apply()
    }

    fun getAccessToken(): String? {
        val encrypted = prefs.getString(KEY_ACCESS_TOKEN, null) ?: return null
        return decrypt(encrypted)
    }

    fun getRefreshToken(): String? {
        val encrypted = prefs.getString(KEY_REFRESH_TOKEN, null) ?: return null
        return decrypt(encrypted)
    }

    fun getUserId(): String? {
        val encrypted = prefs.getString(KEY_USER_ID, null) ?: return null
        return decrypt(encrypted)
    }

    fun getRole(): String? {
        val encrypted = prefs.getString(KEY_ROLE, null) ?: return null
        return decrypt(encrypted)
    }

    fun clear() {
        prefs.edit().clear().apply()
    }

    companion object {
        private const val PREFS_NAME = "tb_keystore_secured_tokens"
        private const val KEYSTORE_PROVIDER = "AndroidKeyStore"
        private const val KEY_ALIAS = "ThinkBuddyTokenKey"
        private const val TRANSFORMATION = "AES/GCM/NoPadding"
        private const val GCM_IV_LENGTH = 12
        private const val GCM_TAG_LENGTH = 128

        private const val KEY_ACCESS_TOKEN = "enc_access_token"
        private const val KEY_REFRESH_TOKEN = "enc_refresh_token"
        private const val KEY_USER_ID = "enc_user_id"
        private const val KEY_ROLE = "enc_role"
    }
}
