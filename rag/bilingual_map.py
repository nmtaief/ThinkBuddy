def translate_chapter_title_en(bn_title: str, subject: str = "", chapter_number: int = 1) -> str:
    """Resolve a canonical English chapter title from a Bangla NCTB chapter title."""
    cleaned = (bn_title or "").strip()
    if cleaned in BN_TO_EN_CHAPTER_MAP:
        return BN_TO_EN_CHAPTER_MAP[cleaned]
    for k, v in BN_TO_EN_CHAPTER_MAP.items():
        if k in cleaned or cleaned in k:
            return v
    if subject:
        return f"{subject.replace('_', ' ').title()} Chapter {chapter_number}"
    return f"Chapter {chapter_number}"
