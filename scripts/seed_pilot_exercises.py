async def seed_pilot():
    async with AsyncSessionLocal() as session:
        for ex in PILOT_EXERCISES:
            stmt = text("""
                INSERT INTO exercise_items (
                    id, book_id, chapter_id, exercise_label, question_no, subpart,
                    question_text, printed_page, pdf_page_index, has_figure,
                    figure_note, item_type, ocr_confidence, status, source, answer_key
                ) VALUES (
                    :id, :book_id, :chapter_id, :exercise_label, :question_no, :subpart,
                    :question_text, :printed_page, :pdf_page_index, :has_figure,
                    :figure_note, :item_type, :ocr_confidence, :status, :source, :answer_key
                )
                ON CONFLICT (chapter_id, exercise_label, question_no, subpart) DO UPDATE
                SET question_text = EXCLUDED.question_text,
                    printed_page = EXCLUDED.printed_page,
                    pdf_page_index = EXCLUDED.pdf_page_index,
                    answer_key = EXCLUDED.answer_key,
                    updated_at = NOW();
            """)
            await session.execute(stmt, ex)
        await session.commit()
        print(f"Successfully seeded {len(PILOT_EXERCISES)} pilot exercises for Class 8 Math Chapter 1.")


if __name__ == "__main__":
    asyncio.run(seed_pilot())

