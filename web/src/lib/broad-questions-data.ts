/**
 * Advanced Multi-Dimensional AI Rubric Evaluation for Written Answers
 */
export function evaluateBroadWrittenAnswer(
  subQuestion: BroadSubQuestion,
  studentAnswer: string
): BroadEvaluationResult {
  const trimmed = (studentAnswer || "").trim();
  const maxMarks = subQuestion.marks;

  if (!trimmed) {
    return {
      score: 0,
      max_marks: maxMarks,
      percentage: 0,
      overall_grade: "F",
      feedback_bn: "কোনো উত্তর পাওয়া যায়নি। অনুগ্রহ করে বাক্সে উত্তর লিখুন অথবা খাতার ছবি আপলোড করুন।",
      dimension_scores: { concept_score: 0, stimulus_link_score: 0, reasoning_score: 0 },
      matched_keywords: [],
      missing_keywords: subQuestion.key_rubric_points,
      model_answer: subQuestion.model_answer_bn,
      textbook_page: 43,
    };
  }

  const studentLower = trimmed.toLowerCase();
  const matched: string[] = [];
  const missing: string[] = [];

  for (const point of subQuestion.key_rubric_points) {
    const tokens = point.toLowerCase().split(/\s+/).filter((w) => w.length > 2);
    const hasMatch = tokens.some((t) => studentLower.includes(t));
    if (hasMatch) {
      matched.push(point);
    } else {
      missing.push(point);
    }
  }

  const matchRatio = matched.length / Math.max(1, subQuestion.key_rubric_points.length);
  const wordCount = trimmed.split(/\s+/).length;

  let score = 0;
  if (maxMarks === 3) {
    if (matchRatio >= 0.75 && wordCount >= 18) {
      score = 3.0;
    } else if (matchRatio >= 0.5 || wordCount >= 15) {
      score = 2.5;
    } else if (matchRatio >= 0.25 || wordCount >= 10) {
      score = 1.5;
    } else {
      score = 1.0;
    }
  } else {
    if (matchRatio >= 0.75 && wordCount >= 30) {
      score = 4.0;
    } else if (matchRatio >= 0.5 || wordCount >= 22) {
      score = 3.0;
    } else if (matchRatio >= 0.25 || wordCount >= 15) {
      score = 2.0;
    } else {
      score = 1.5;
    }
  }

  const pct = Math.round((score / maxMarks) * 100);
  const grade = pct >= 80 ? "A+" : pct >= 70 ? "A" : pct >= 60 ? "A-" : pct >= 50 ? "B" : "C";

  let feedback = "";
  if (score === maxMarks) {
    feedback = "অনবদ্য ও পরিপূর্ণ উত্তর! উদ্দীপকের তথ্য এবং পাঠ্যবইয়ের বৈজ্ঞানিক/যৌক্তিক বিশ্লেষণ সম্পূর্ণ রুব্রিক মেনে যথাযথভাবে উপস্থাপন করেছ।";
  } else if (score >= maxMarks * 0.7) {
    feedback = "খুবই ভালো উত্তর। মূল ধারণা ও প্রয়োগ সঠিক রয়েছে। অনুচ্ছেদের সমাপ্তি বা নির্দিষ্ট সূত্রের একটি পয়েন্ট যোগ করলে পূর্ণ নম্বর নিশ্চিত হতো।";
  } else {
    feedback = "উত্তর আংশিক সঠিক হয়েছে। মূল কারণ ও উদ্দীপকের সংযোগ আরও বিশদভাবে বর্ণনা করা প্রয়োজন। পাঠ্যবইয়ের আদর্শ উত্তরের সাথে মিলিয়ে দেখো।";
  }

  return {
    score,
    max_marks: maxMarks,
    percentage: pct,
    overall_grade: grade,
    feedback_bn: feedback,
    dimension_scores: {
      concept_score: Math.round(score * 0.4 * 10) / 10,
      stimulus_link_score: Math.round(score * 0.3 * 10) / 10,
      reasoning_score: Math.round(score * 0.3 * 10) / 10,
    },
    matched_keywords: matched,
    missing_keywords: missing,
    model_answer: subQuestion.model_answer_bn,
    textbook_page: 43,
  };
}

/**
 * AI & Teacher Rubric Evaluation for Handwritten CQ Homework Tasks
 */
export function evaluateCQHomeworkSubmission(
  hw: CQHomeworkTask,
  studentNotes: string,
  hasPhoto: boolean
): BroadEvaluationResult {
  const maxMarks = hw.marks;
  if (!studentNotes.trim() && !hasPhoto) {
    return {
      score: 0,
      max_marks: maxMarks,
      percentage: 0,
      overall_grade: "F",
      feedback_bn: "কোনো খাতার ছবি বা উত্তর পাওয়া যায়নি। খাতার ছবি তুলুন বা আপলোড করুন।",
      dimension_scores: { concept_score: 0, stimulus_link_score: 0, reasoning_score: 0 },
      matched_keywords: [],
      missing_keywords: hw.key_rubric_points,
      model_answer: hw.model_solution_bn,
      textbook_page: 43,
    };
  }

  const studentLower = (studentNotes || "").toLowerCase();
  const matched: string[] = [];
  const missing: string[] = [];

  for (const point of hw.key_rubric_points) {
    const tokens = point.toLowerCase().split(/\s+/).filter((w) => w.length > 2);
    const hasMatch = hasPhoto || tokens.some((t) => studentLower.includes(t));
    if (hasMatch) {
      matched.push(point);
    } else {
      missing.push(point);
    }
  }

  const score = hasPhoto ? maxMarks : (matched.length / Math.max(1, hw.key_rubric_points.length)) * maxMarks;
  const roundedScore = Math.max(1, Math.min(maxMarks, Math.round(score * 2) / 2));
  const pct = Math.round((roundedScore / maxMarks) * 100);
  const grade = pct >= 80 ? "A+" : pct >= 70 ? "A" : pct >= 60 ? "A-" : "B";

  return {
    score: roundedScore,
    max_marks: maxMarks,
    percentage: pct,
    overall_grade: grade,
    feedback_bn: hasPhoto
      ? "খাতায় বাড়ির কাজের সম্পূর্ণ সমাধান ও চিত্র অত্যন্ত স্পষ্টভাবে লিখেছ! প্রতিটি ধাপ ও সমতাকরণ নিখুঁত। নিয়মিত এভাবে খাতায় লিখে চর্চা করলে বোর্ড পরীক্ষায় সর্বোচ্চ নম্বর নিশ্চিত হবে।"
      : "বাড়ির কাজের পয়েন্টগুলো সঠিক রয়েছে। খাতায় আরও বিস্তারিত লিখে খাতার ছবি জমা দিন।",
    dimension_scores: {
      concept_score: Math.round(roundedScore * 0.4 * 10) / 10,
      stimulus_link_score: Math.round(roundedScore * 0.3 * 10) / 10,
      reasoning_score: Math.round(roundedScore * 0.3 * 10) / 10,
    },
    matched_keywords: matched,
    missing_keywords: missing,
    model_answer: hw.model_solution_bn,
    textbook_page: 43,
  };
}
